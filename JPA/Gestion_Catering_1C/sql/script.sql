DROP TABLE COMPRA CASCADE CONSTRAINTS;

DROP TABLE CLIENTE CASCADE CONSTRAINTS;

DROP TABLE MENU CASCADE CONSTRAINTS;

DROP TABLE BONOCLIENTE CASCADE CONSTRAINTS;


CREATE TABLE BONOCLIENTE(
	IDBONOCLIENTE INTEGER PRIMARY KEY,
	BONO VARCHAR(50) NOT NULL,
    DESCUENTO FLOAT
);

CREATE TABLE CLIENTE(
	CIF VARCHAR(10) PRIMARY KEY,
    DESCRIPCION VARCHAR(100) NOT NULL,
	DIRECCION VARCHAR(100),
  	CP VARCHAR(5),
 	CIUDAD VARCHAR(20),
	IDBONOCLIENTE INTEGER NOT NULL,
	FOREIGN KEY (IDBONOCLIENTE) REFERENCES BONOCLIENTE(IDBONOCLIENTE)
);

CREATE TABLE MENU(
	IDMENU INTEGER PRIMARY KEY,
	DESCRIPCION VARCHAR(30),
	PRECIO FLOAT NOT NULL
);

CREATE TABLE COMPRA(
	FECHA TIMESTAMP,
	CIF VARCHAR(10),
	IDMENU INTEGER,
    PERSONAS INTEGER NOT NULL CHECK (PERSONAS > 0),
    IMPORTE FLOAT NOT NULL CHECK (IMPORTE > 0),
	PRIMARY KEY (FECHA, CIF),
	FOREIGN KEY (CIF) REFERENCES CLIENTE(CIF),
	FOREIGN KEY (IDMENU) REFERENCES MENU(IDMENU)
);

